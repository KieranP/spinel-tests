# Array#<=>

p([1, 2, 3] <=> [1, 2, 4])

a001 = [1, 2, 3]
p a001.class
p(a001 <=> [1, 2, 4])

a002 = [1, 2, 3]
b002 = [1, 2, 4]
p b002.class
p(a002 <=> b002)

a003 = [1, 2, 3]
b003 = [1, 2, 4]
c003 = (a003 <=> b003)
p c003.class
p c003

